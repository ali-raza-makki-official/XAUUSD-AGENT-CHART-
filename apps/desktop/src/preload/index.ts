const on =
  <T>(channel: string) =>
  (cb: (v: T) => void) => {
    const h = (_e: IpcRendererEvent, v: T) => cb(v);
    ipcRenderer.on(channel, h);
    return () => ipcRenderer.removeListener(channel, h);
  };

